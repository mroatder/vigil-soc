<script setup>
import { computed } from 'vue'
import vigilLogo from '../favicon.svg'

const props = defineProps({
  report: { type: Object, required: true },
  lang: { type: String, required: true },
  author: { type: String, default: '' },
  facts: { type: Object, default: () => ({}) },
  issue: { type: Object, default: () => ({}) }
})

const COPY = {
  th: {
    title: 'รายงานเหตุการณ์ด้านความปลอดภัย', systemLine: 'ระบบวิเคราะห์เหตุการณ์ความปลอดภัย', issueTitle: 'ข้อมูลการออกรายงาน', reportId: 'เลขที่รายงาน', issuedAt: 'วันเวลาที่ออกรายงาน', system: 'ระบบที่สร้างรายงาน', dataSource: 'แหล่งข้อมูล', dataSourceValue: 'Wazuh SIEM และ Log จากอุปกรณ์ Firewall', engine: 'การวิเคราะห์', engineLocal: 'Local AI ภายในเครื่องขององค์กร', engineClaude: 'Local AI ภายในเครื่องและ Claude โดยส่งเฉพาะข้อมูลที่ปิดบังค่าสำคัญแล้ว', severity: 'ระดับความสำคัญ', time: 'เวลาเกิดเหตุ', action: 'การกระทำของระบบ', author: 'ผู้จัดทำ', source: 'วิเคราะห์โดย',
    eventConfidence: 'ความมั่นใจของเหตุการณ์', impactConfidence: 'ความมั่นใจของผลกระทบ',
    missing: 'ยังไม่มีรายงานภาษานี้ ให้สร้างใหม่ด้วย Local AI หรือส่งให้ Claude',
    result: 'ผลลัพธ์', summary: 'สรุปเหตุการณ์', facts: 'ใคร ทำอะไร และใครป้องกัน', impact: 'ผลกระทบ', timeline: 'ลำดับเหตุการณ์',
    status: 'สถานะปัจจุบัน', actions: 'สิ่งที่ต้องดำเนินการ', unknown: 'สิ่งที่ยังไม่ยืนยัน', decision: 'สิ่งที่ต้องการให้ตัดสินใจ',
    factRows: { source: 'ใครหรืออะไรเป็นต้นทาง', target: 'เป้าหมาย', attack: 'ทำอะไร', defense: 'ใครป้องกัน' },
    impactRows: { impact_systems: 'ระบบ', impact_data: 'ข้อมูล', impact_service: 'บริการและผู้ใช้' },
    owner: 'ผู้รับผิดชอบ', task: 'งาน', due: 'กำหนด',
    defense: 'ผลการป้องกัน', defenseProof: action => `ยืนยันจาก Log ของอุปกรณ์ ACTION=${action}`,
    device: (waf, name) => `${waf ? 'WAF บน Firewall' : 'Firewall'}${name ? ` ${name}` : ''}`,
    blocked: who => `${who} บล็อกคำขอนี้สำเร็จ`, allowed: who => `${who} ไม่ได้บล็อกคำขอนี้`, noState: 'ไม่พบผลการบล็อกใน Log',
    severityReason: 'เหตุผลของระดับความสำคัญ', businessRisk: 'ความเสี่ยงต่อธุรกิจ', evidence: 'หลักฐานจาก Log',
    evidenceRows: { srcip: 'IP ต้นทาง', country: 'ประเทศตาม GeoIP', dstip: 'เป้าหมาย', attack: 'ประเภทการโจมตี', signature: 'Signature', url: 'URL ที่ถูกร้องขอ', device: 'อุปกรณ์ที่ตรวจพบ', action: 'Action', rule: 'Wazuh Rule', time: 'เวลาจากอุปกรณ์' }
  },
  en: {
    title: 'Security Incident Report', systemLine: 'Security Event Analysis System', issueTitle: 'Report information', reportId: 'Report no.', issuedAt: 'Issued at', system: 'Generated by', dataSource: 'Data source', dataSourceValue: 'Wazuh SIEM and firewall device logs', engine: 'Analysis', engineLocal: 'On-premises Local AI', engineClaude: 'On-premises Local AI and Claude, using masked data only', severity: 'Severity', time: 'Event time', action: 'System action', author: 'Prepared by', source: 'Analyzed by',
    eventConfidence: 'Event confidence', impactConfidence: 'Impact confidence',
    missing: 'This language is not available yet. Generate the report again or send it to Claude.',
    result: 'Result', summary: 'Summary', facts: 'Who did what, and who stopped it', impact: 'Impact', timeline: 'Timeline',
    status: 'Current status', actions: 'Required actions', unknown: 'Not yet confirmed', decision: 'Decision needed',
    factRows: { source: 'Source', target: 'Target', attack: 'Activity', defense: 'Defended by' },
    impactRows: { impact_systems: 'Systems', impact_data: 'Data', impact_service: 'Services and users' },
    owner: 'Owner', task: 'Task', due: 'Due',
    defense: 'Defense result', defenseProof: action => `Confirmed by the device log, ACTION=${action}`,
    device: (waf, name) => `${waf ? 'WAF on firewall' : 'Firewall'}${name ? ` ${name}` : ''}`,
    blocked: who => `${who} successfully blocked this request`, allowed: who => `${who} did not block this request`, noState: 'No block result was found in the log',
    severityReason: 'Why this severity', businessRisk: 'Business risk', evidence: 'Evidence from the log',
    evidenceRows: { srcip: 'Source IP', country: 'GeoIP country', dstip: 'Target', attack: 'Attack type', signature: 'Signature', url: 'Requested URL', device: 'Detected by', action: 'Action', rule: 'Wazuh rule', time: 'Device time' }
  }
}

const copy = computed(() => COPY[props.lang])
const fields = computed(() => props.report.reports[props.lang] || null)
const text = key => fields.value?.[key]?.text || ''
const items = key => fields.value?.[key]?.items || []
const rows = labels => Object.entries(labels).filter(([key]) => text(key)).map(([key, label]) => ({ key, label, value: text(key) }))
const factRows = computed(() => {
  const who = copy.value.device(props.facts.isWaf, props.facts.device)
  const derived = {
    source: [props.facts.srcip, props.facts.country].filter(Boolean).join(', '),
    target: props.facts.dstip,
    attack: props.facts.attack,
    defense: defenseLine.value && props.facts.action ? `${defenseLine.value}` : (props.facts.device ? who : '')
  }
  return Object.entries(copy.value.factRows)
    .map(([key, label]) => ({ key, label, value: text(key) || derived[key] }))
    .filter(row => row.value)
})
const evidenceRows = computed(() => Object.entries(copy.value.evidenceRows)
  .filter(([key]) => props.facts[key])
  .map(([key, label]) => ({ key, label, value: props.facts[key] })))
const defenseLine = computed(() => {
  const who = copy.value.device(props.facts.isWaf, props.facts.device)
  if (props.facts.state === 'blocked') return copy.value.blocked(who)
  if (props.facts.state === 'allowed') return copy.value.allowed(who)
  return ''
})
const impactRows = computed(() => rows(copy.value.impactRows))
const summary = computed(() => props.report.summary || {})
const metadata = computed(() => [
  [copy.value.severity, summary.value.severity],
  [copy.value.time, summary.value.event_time || props.facts.time],
  [copy.value.action, summary.value.action],
  [copy.value.eventConfidence, summary.value.event_confidence],
  [copy.value.impactConfidence, summary.value.impact_confidence],
  [copy.value.author, props.author]
].filter(([, value]) => value))
// New reports use "who | task | when". Older saved reports hold plain sentences.
const actions = computed(() => items('actions').map(item => item.split('|').map(part => part.trim())))
const hasOwners = computed(() => actions.value.some(parts => parts.length > 1))
const issuedAt = computed(() => {
  if (!props.issue.at) return ''
  const locale = props.lang === 'th' ? 'th-TH-u-ca-gregory' : 'en-GB'
  return new Intl.DateTimeFormat(locale, { dateStyle: 'medium', timeStyle: 'short', hour12: false }).format(props.issue.at)
})
const issueRows = computed(() => [
  [copy.value.reportId, props.issue.id],
  [copy.value.issuedAt, issuedAt.value],
  [copy.value.system, `Vigil${props.issue.version ? ` v${props.issue.version}` : ''}`],
  [copy.value.dataSource, copy.value.dataSourceValue],
  [copy.value.engine, summary.value.source === 'local' ? copy.value.engineLocal : copy.value.engineClaude]
].filter(([, value]) => value))
</script>

<template>
  <div class="bg-white text-[#1c1c1e] font-sans" :lang="lang">
    <template v-if="fields">
      <header class="flex items-center justify-between gap-4 pb-4 mb-4 border-b border-[#d8d8dc] break-inside-avoid">
        <img v-if="issue.logo" :src="issue.logo" alt="Company logo" class="h-6 w-auto">
        <div class="flex items-center gap-2 text-right ml-auto">
          <div>
            <p class="text-[15px] leading-5 font-medium">Vigil</p>
            <p class="text-[11px] leading-4 text-[#55555a]">{{ copy.systemLine }}</p>
          </div>
          <img :src="vigilLogo" alt="" class="w-7 h-7">
        </div>
      </header>
      <p class="text-[13px] text-[#55555a] flex flex-wrap justify-between gap-x-3"><span>{{ copy.title }}</span><span v-if="issue.id">{{ issue.id }}</span></p>
      <h1 class="text-[25px] leading-[1.35] font-medium mt-1">{{ text('title') || summary.verdict }}</h1>
      <dl class="grid grid-cols-2 sm:grid-cols-3 print:grid-cols-3 gap-x-6 gap-y-2 mt-5 py-4 border-y border-[#d8d8dc]">
        <div v-for="[label, value] in metadata" :key="label"><dt class="text-[12px] text-[#55555a]">{{ label }}</dt><dd class="text-[15px] font-normal">{{ value }}</dd></div>
      </dl>

      <section class="mt-5 break-inside-avoid border-l-4 border-[#1c1c1e] pl-3">
        <h2 class="text-[13px] text-[#55555a] font-normal">{{ copy.defense }}</h2>
        <p class="text-[20px] leading-8 font-medium">{{ defenseLine || copy.noState }}</p>
        <p v-if="facts.action" class="text-[13px] text-[#55555a]">{{ copy.defenseProof(facts.action) }}</p>
        <p v-if="text('result')" class="text-[15px] leading-7 mt-1"><span class="text-[#55555a]">{{ copy.result }}: </span>{{ text('result') }}</p>
      </section>

      <section v-if="text('summary')" class="mt-6 break-inside-avoid">
        <h2 class="text-[17px] font-medium">{{ copy.summary }}</h2>
        <p class="mt-1 text-[15px] leading-7">{{ text('summary') }}</p>
      </section>

      <section v-if="factRows.length" class="mt-6 break-inside-avoid">
        <h2 class="text-[17px] font-medium">{{ copy.facts }}</h2>
        <table class="w-full mt-2 text-[14px] leading-6 border-collapse">
          <tbody>
            <tr v-for="row in factRows" :key="row.key" class="border-t border-[#d8d8dc]">
              <th scope="row" class="w-[32%] py-2 pr-3 text-left align-top font-normal text-[#55555a]">{{ row.label }}</th>
              <td class="py-2 align-top break-words">{{ row.value }}</td>
            </tr>
          </tbody>
        </table>
      </section>

      <section v-if="text('impact') || impactRows.length" class="mt-6 break-inside-avoid">
        <h2 class="text-[17px] font-medium">{{ copy.impact }}</h2>
        <p v-if="text('impact')" class="mt-1 text-[15px] leading-7">{{ text('impact') }}</p>
        <table v-if="impactRows.length" class="w-full mt-2 text-[14px] leading-6 border-collapse">
          <tbody>
            <tr v-for="row in impactRows" :key="row.key" class="border-t border-[#d8d8dc]">
              <th scope="row" class="w-[32%] py-2 pr-3 text-left align-top font-normal text-[#55555a]">{{ row.label }}</th>
              <td class="py-2 align-top break-words">{{ row.value }}</td>
            </tr>
          </tbody>
        </table>
      </section>

      <section v-if="text('severity_reason')" class="mt-6 break-inside-avoid">
        <h2 class="text-[17px] font-medium">{{ copy.severityReason }}</h2>
        <p class="mt-1 text-[15px] leading-7">{{ text('severity_reason') }}</p>
      </section>

      <section v-if="text('business_risk')" class="mt-6 break-inside-avoid">
        <h2 class="text-[17px] font-medium">{{ copy.businessRisk }}</h2>
        <p class="mt-1 text-[15px] leading-7">{{ text('business_risk') }}</p>
      </section>

      <section v-if="items('timeline').length" class="mt-6 break-inside-avoid">
        <h2 class="text-[17px] font-medium">{{ copy.timeline }}</h2>
        <ol class="mt-1 text-[15px] leading-7">
          <li v-for="(item, index) in items('timeline')" :key="index">{{ item }}</li>
        </ol>
      </section>

      <section v-if="text('status')" class="mt-6 break-inside-avoid">
        <h2 class="text-[17px] font-medium">{{ copy.status }}</h2>
        <p class="mt-1 text-[15px] leading-7">{{ text('status') }}</p>
      </section>

      <section v-if="actions.length" class="mt-6 break-inside-avoid">
        <h2 class="text-[17px] font-medium">{{ copy.actions }}</h2>
        <table v-if="hasOwners" class="w-full mt-2 text-[14px] leading-6 border-collapse">
          <thead>
            <tr class="text-left text-[#55555a]"><th scope="col" class="w-[24%] pb-1 pr-3 font-normal">{{ copy.owner }}</th><th scope="col" class="pb-1 pr-3 font-normal">{{ copy.task }}</th><th scope="col" class="w-[20%] pb-1 font-normal">{{ copy.due }}</th></tr>
          </thead>
          <tbody>
            <tr v-for="(parts, index) in actions" :key="index" class="border-t border-[#d8d8dc]">
              <template v-if="parts.length > 1">
                <td class="py-2 pr-3 align-top">{{ parts[0] }}</td><td class="py-2 pr-3 align-top break-words">{{ parts[1] }}</td><td class="py-2 align-top">{{ parts[2] }}</td>
              </template>
              <td v-else colspan="3" class="py-2 align-top break-words">{{ parts[0] }}</td>
            </tr>
          </tbody>
        </table>
        <ul v-else class="mt-1 pl-5 list-disc text-[15px] leading-7">
          <li v-for="(parts, index) in actions" :key="index">{{ parts[0] }}</li>
        </ul>
      </section>

      <section v-if="items('unknown').length" class="mt-6 break-inside-avoid">
        <h2 class="text-[17px] font-medium">{{ copy.unknown }}</h2>
        <ul class="mt-1 pl-5 list-disc text-[15px] leading-7">
          <li v-for="(item, index) in items('unknown')" :key="index">{{ item }}</li>
        </ul>
      </section>

      <section v-if="text('decision')" class="mt-6 break-inside-avoid">
        <h2 class="text-[17px] font-medium">{{ copy.decision }}</h2>
        <p class="mt-1 text-[15px] leading-7">{{ text('decision') }}</p>
      </section>

      <section v-if="evidenceRows.length" class="mt-6 break-inside-avoid">
        <h2 class="text-[17px] font-medium">{{ copy.evidence }}</h2>
        <table class="w-full mt-2 text-[13px] leading-5 border-collapse">
          <tbody>
            <tr v-for="row in evidenceRows" :key="row.key" class="border-t border-[#d8d8dc]">
              <th scope="row" class="w-[32%] py-1.5 pr-3 text-left align-top font-normal text-[#55555a]">{{ row.label }}</th>
              <td class="py-1.5 align-top [overflow-wrap:anywhere]">{{ row.value }}</td>
            </tr>
          </tbody>
        </table>
      </section>

      <section class="mt-6 pt-4 border-t-2 border-[#1c1c1e] break-inside-avoid">
        <h2 class="text-[13px] font-medium">{{ copy.issueTitle }}</h2>
        <dl class="grid grid-cols-[32%_1fr] gap-x-3 mt-1 text-[12px] leading-5">
          <template v-for="[label, value] in issueRows" :key="label">
            <dt class="text-[#55555a]">{{ label }}</dt><dd>{{ value }}</dd>
          </template>
        </dl>
      </section>
    </template>
    <p v-else class="text-[15px]">{{ copy.missing }}</p>
  </div>
</template>
